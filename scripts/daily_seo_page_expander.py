def add_daily_seo_batch(batch_size=10):
    print(f"🚀 Running Daily SEO Page Expander (Target Batch Size: {batch_size} pages/day)...")
    if not os.path.exists(SITEMAP_PATH):
        print(f"⚠️ Sitemap file not found at: {SITEMAP_PATH}")
        return

    with open(SITEMAP_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    added_count = 0
    for page_type, slug in UPCOMING_PAGE_POOL:
        url_str = f"/{page_type}/{slug}" if page_type != "blog" else f"/blog/{slug}"
        if url_str in content or slug in content:
            continue
            
        print(f"   [+] Adding fresh daily SEO page: {url_str}")
        added_count += 1
        if added_count >= batch_size:
            break

    if added_count == 0:
        print("✅ Daily SEO Page Expander: All queued pool pages are already live in sitemap!")
    else:
        print(f"🎉 Successfully added {added_count} new SEO pages to the daily publishing schedule!")

if __name__ == "__main__":
    add_daily_seo_batch(10)
